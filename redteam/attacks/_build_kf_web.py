"""Generates kf_web.json (XSS via invoice fields in the Kontrola faktur page)."""
import json
from pathlib import Path

P1 = '<img src=x onerror="window.__pwned=1">'
P2 = "<script>window.__pwned=1</script>"
P3 = '"><svg onload=window.__pwned=1>'
P4 = '" autofocus onfocus="window.__pwned=1'
P5 = "</textarea><img src=x onerror=window.__pwned=1>"
P6 = '<iframe srcdoc="<script>parent.__pwned=1</script>"></iframe>'
P7 = "<details open ontoggle=window.__pwned=1>x</details>"
P8 = "</td></tr></table><img src=x onerror=alert(1)>"
CHECK = [{"oracle": "field_equals", "field": "form_rendered", "value": True}, {"oracle": "no_script_exec"}]
A = []


def add(i, sev, title, field, payload, via="read", check=True, note=None):
    a = {"id": f"KF-W-{i:02d}", "group": "xss", "severity": sev, "title": title,
         "input": {"field": field, "payload": payload, "via": via, "check": check}, "checks": CHECK}
    if note:
        a["note"] = note
    A.append(a)


add(1, "High", "Kontrola: neškodné hodnoty, stránka se vykreslí a nic se nespustí", "invoice_number", "FV-OK-1")
add(2, "High", "XSS: číslo faktury <img onerror>", "invoice_number", P1)
add(3, "High", "XSS: kód položky (sku) <img onerror>", "sku", P1)
add(4, "High", "XSS: poznámka rozbíjí textarea (</textarea><img>)", "note", P5)
add(5, "High", "XSS: číslo objednávky vyskočí z atributu value", "po_number", P4)
add(6, "High", "XSS: bankovní účet <svg onload>", "bank_account", P3)
add(7, "High", "XSS: množství jako <img onerror>", "qty", P1)
add(8, "High", "XSS: cena za kus rozbíjí atribut", "unit_price", P4)
add(9, "High", "XSS: datum vystavení <img onerror>", "issue_date", P1)
add(10, "High", "XSS: IČO dodavatele <img onerror>", "supplier_ico", P1)
add(11, "High", "XSS: poznámka <script> zadaná ručně do formuláře", "note", P2, via="typed")
add(12, "High", "XSS: číslo faktury <svg onload> zadané ručně", "invoice_number", P3, via="typed")
add(13, "High", "XSS: kód položky <details ontoggle>", "sku", P7)
add(14, "High", "XSS: iframe srcdoc v čísle faktury", "invoice_number", P6)
add(15, "High", "XSS: </table><img> v kódu položky", "sku", P8)
add(16, "High", "XSS: název dodavatele z číselníku (books) <img onerror>", "supplier_name", P1,
    note="Master data are trusted; this checks that the page escapes them anyway.")
add(17, "High", "XSS: text dokumentu (document_text) <img onerror>", "document_text", P1)
add(18, "Low", "Sink bez esc: pole 'reader' <img onerror>", "reader", P1)
add(19, "Low", "Sink bez esc: pole 'seconds' (za ${data.seconds} s) <img onerror>", "seconds", P1,
    note="The page puts `seconds` into innerHTML without esc. In real use the server measures it (a number); "
         "only a compromised server or reads.json could send text. Hardening, not an exploit by itself.")
add(20, "Low", "Sink bez esc: pole 'image' (src=\"${docImage}\") rozbije atribut", "image",
    'x" onerror="window.__pwned=1', note="`image` is a server-built path in real use. Hardening note.")
(Path(__file__).parent / "kf_web.json").write_text(json.dumps(
    {"target": "kf_web", "note": "XSS in the local Kontrola faktur page (Playwright). Generated by _build_kf_web.py.",
     "attacks": A}, ensure_ascii=False, indent=1), encoding="utf-8")
print(len(A), "attacks")
